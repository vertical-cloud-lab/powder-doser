# Reference powder of #196 (salt, real size): 0.361/0.425/0.489 mm, 0.3/0.4/0.3 by number
SALT = dict(
    density=2165.0,
    diam_mm=(0.361, 0.425, 0.489),
    frac=(0.3, 0.4, 0.3),
    youngs=2.0e5,          # Pa, reduced as in #180 / #196
    poisson=0.3,
    restitution=0.5,
    mu_pp=0.5, mu_pw=0.4, mu_roll=0.3,
)
