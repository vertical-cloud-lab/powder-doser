def style_axes(ax):
    ax.set_facecolor(SURF)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(INK2)
    ax.tick_params(colors=INK2, labelsize=8)
    ax.xaxis.label.set_color(INK)
    ax.yaxis.label.set_color(INK)
    ax.title.set_color(INK)
    ax.grid(True, color="#e6e5e1", lw=0.6)
    ax.set_axisbelow(True)


def draw_grains(ax, x, z, r, c=None, cmap=None, vmax=None, color="#9a9a96"):
    from matplotlib.collections import EllipseCollection
    if len(x) == 0:
        return None
    ec = EllipseCollection(2 * r, 2 * r, np.zeros_like(r), units="xy", offsets=np.c_[x, z],
                           offset_transform=ax.transData, linewidths=0)
    if c is not None:
        ec.set_array(np.asarray(c))
        ec.set_cmap(cmap)
        ec.set_clim(0, vmax)
    else:
        ec.set_facecolor(color)
    ax.add_collection(ec)
    return ec


def fig_to_array(fig):
    fig.canvas.draw()
    return np.asarray(fig.canvas.buffer_rgba())[:, :, :3].copy()


def save_mp4(frames, path, fps=12):
    import imageio.v2 as imageio
    h, w = frames[0].shape[:2]
    h2, w2 = h - h % 2, w - w % 2
    wr = imageio.get_writer(path, fps=fps, codec="libx264", pixelformat="yuv420p",
                            ffmpeg_params=["-crf", "28", "-preset", "medium"], macro_block_size=1)
    for fr in frames:
        wr.append_data(fr[:h2, :w2])
    wr.close()
