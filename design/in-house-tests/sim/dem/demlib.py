D50 = 0.425e-3


def rayleigh_dt(d_min, rho=SALT["density"], E=SALT["youngs"], nu=SALT["poisson"]):
    G = E / (2 * (1 + nu))
    return math.pi * 0.5 * d_min * math.sqrt(rho / G) / (0.1631 * nu + 0.8766)


def default_dt(scale=1.0):
    return 0.2 * rayleigh_dt(SALT["diam_mm"][0] * 1e-3 * scale)


def mean_grain_volume(scale=1.0):
    d = np.array(SALT["diam_mm"]) * 1e-3 * scale
    return float(np.sum(np.array(SALT["frac"]) * math.pi / 6 * d ** 3))


def grain_mass_mean(scale=1.0):
    return SALT["density"] * mean_grain_volume(scale)


def bond_number(ced, d, E=SALT["youngs"], nu=SALT["poisson"], rho=SALT["density"], g=9.81):
    """Pull-off Bond number of a Hertz + SJKR contact between two equal spheres (see #196 run 2)."""
    R = 0.5 * d
    Es = E / (2 * (1 - nu ** 2))
    A = ced * math.pi * R
    B = 4.0 / 3.0 * Es * math.sqrt(R / 2)
    F = 4.0 / 27.0 * A ** 3 / B ** 2
    return F / (SALT["density"] * math.pi / 6 * d ** 3 * g)


