def write_stl(path, tris, name="mesh"):
    with open(path, "w") as f:
        f.write(f"solid {name}\n")
        for t in tris:
            f.write("facet normal 0 0 0\nouter loop\n")
            for q in t:
                f.write(f"vertex {q[0]:.6e} {q[1]:.6e} {q[2]:.6e}\n")
            f.write("endloop\nendfacet\n")
        f.write(f"endsolid {name}\n")


def revolve(profile, n=96):
    """Surface of revolution about z from a list of (r, z) points; returns triangles."""
    tris = []
    for (ra, za), (rb, zb) in zip(profile[:-1], profile[1:]):
        for i in range(n):
            a0, a1 = 2 * math.pi * i / n, 2 * math.pi * (i + 1) / n
            p00 = (ra * math.cos(a0), ra * math.sin(a0), za)
            p01 = (ra * math.cos(a1), ra * math.sin(a1), za)
            p10 = (rb * math.cos(a0), rb * math.sin(a0), zb)
            p11 = (rb * math.cos(a1), rb * math.sin(a1), zb)
            if ra > 0:
                tris.append((p00, p01, p11))
            if rb > 0:
                tris.append((p00, p11, p10))
    return tris


