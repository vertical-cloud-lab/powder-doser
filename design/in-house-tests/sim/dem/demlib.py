def sample_psd(n, rng, scale=1.0):
    d = np.array(SALT["diam_mm"]) * 1e-3 * scale
    return rng.choice(d, size=n, p=np.array(SALT["frac"]))


def frozen_atoms_block(xyz, diam, density=SALT["density"], first_id=1, group="frozen", atype=1):
    """create_atoms lines for frozen spheres; diameters set by contiguous id ranges per size."""
    order = np.argsort(diam, kind="stable")
    xyz, diam = np.asarray(xyz)[order], np.asarray(diam)[order]
    lines = [f"create_atoms {atype} single {p[0]:.6e} {p[1]:.6e} {p[2]:.6e} units box" for p in xyz]
    n = len(diam)
    i = 0
    ids = first_id
    while i < n:
        j = i
        while j < n and abs(diam[j] - diam[i]) < 1e-12:
            j += 1
        lines.append(f"set atom {ids + i}*{ids + j - 1} diameter {diam[i]:.6e}")
        lines.append(f"set atom {ids + i}*{ids + j - 1} density {density}")
        i = j
    lines.append(f"group {group} id <> {first_id} {first_id + n - 1}")
    return "\n".join(lines) + "\n", xyz, diam


def rsa_monolayer(region_fn, area_box, rng, coverage=0.5, scale=1.0, z0=0.0, max_try=200000):
    """Random sequential adsorption of PSD spheres resting on the plane z = z0.

    region_fn(x, y, r) -> bool says whether a sphere centre may go there. area_box = (x0, x1, y0, y1).
    Returns xyz (centres) and diameters.
    """
    x0, x1, y0, y1 = area_box
    pts, rad = [], []
    area = 0.0
    total = (x1 - x0) * (y1 - y0)
    tries = 0
    from collections import defaultdict
    cell = 0.6e-3 * scale
    grid = defaultdict(list)
    while tries < max_try:
        tries += 1
        r = 0.5 * sample_psd(1, rng, scale)[0]
        x, y = rng.uniform(x0, x1), rng.uniform(y0, y1)
        if not region_fn(x, y, r):
            continue
        ci, cj = int(x // cell), int(y // cell)
        ok = True
        for di in (-1, 0, 1):
            for dj in (-1, 0, 1):
                for k in grid[(ci + di, cj + dj)]:
                    xx, yy, rr = pts[k][0], pts[k][1], rad[k]
                    if (x - xx) ** 2 + (y - yy) ** 2 < 4 * r * rr * 1.0001:
                        ok = False
                        break
                if not ok:
                    break
            if not ok:
                break
        if not ok:
            continue
        grid[(ci, cj)].append(len(pts))
        pts.append((x, y, z0 + r))
        rad.append(r)
        area += math.pi * r * r
        if area / total >= coverage:
            break
    return np.array(pts), 2 * np.array(rad)


def run_liggghts(workdir, infile, log="log.liggghts", screen="screen.txt"):
    env = dict(os.environ, OMP_NUM_THREADS="1")
    t0 = time.time()
    p = subprocess.run(["liggghts", "-in", infile, "-log", log, "-echo", "none", "-screen", screen],
                       cwd=workdir, capture_output=True, text=True, env=env)
    wall = time.time() - t0
    tail = ""
    try:
        with open(os.path.join(workdir, screen)) as f:
            tail = f.read()[-3000:]
    except OSError:
        pass
    return p.returncode, wall, tail + p.stdout[-1000:] + p.stderr[-1000:]


def read_dump(path):
    """LIGGGHTS custom text dump -> (step, dict of columns)."""
    with open(path) as f:
        f.readline()
        step = int(f.readline())
        f.readline()
        n = int(f.readline())
        for _ in range(4):
            f.readline()
        cols = f.readline().split()[2:]
        if n == 0:
            return step, {c: np.zeros(0) for c in cols}
        A = np.fromstring(f.read(), sep=" ")
    A = A.reshape(n, len(cols))
    return step, {c: A[:, i] for i, c in enumerate(cols)}


def dump_series(pattern):
    files = glob.glob(pattern)
    key = lambda p: int(re.findall(r"(\d+)", os.path.basename(p))[-1])  # noqa: E731
    return sorted(files, key=key)


def save_frames(path, t, frames, extra=None, max_frames=150, max_bytes=3.0e6, nmax=None):
    """Decimated trajectory for animation: npz with t[F], pos[F,N,3] (mm, float16), r[N] (mm), id[N].

    frames: list of dicts with 'id', 'x', 'y', 'z', 'radius' (SI). Grains absent from a frame are NaN.
    pos is stored Fortran-ordered (frame index fastest), so grains at rest compress to almost nothing;
    np.load gives the same [F,N,3] array.
    """
    if len(frames) > max_frames:
        sel = np.unique(np.linspace(0, len(frames) - 1, max_frames).round().astype(int))
        frames = [frames[i] for i in sel]
        t = np.asarray(t)[sel]
    ids = np.unique(np.concatenate([f["id"] for f in frames]).astype(np.int64))
    if nmax is not None and len(ids) > nmax:
        ids = np.sort(np.random.default_rng(0).choice(ids, nmax, replace=False))
    index = {int(i): k for k, i in enumerate(ids)}
    F, N = len(frames), len(ids)
    pos = np.full((F, N, 3), np.nan, dtype=np.float32)
    r = np.full(N, np.nan, dtype=np.float32)
    for fi, f in enumerate(frames):
        k = np.searchsorted(ids, f["id"].astype(np.int64))
        ok = (k < N) & (ids[np.minimum(k, N - 1)] == f["id"].astype(np.int64))
        k = k[ok]
        pos[fi, k, 0] = f["x"][ok] * 1e3
        pos[fi, k, 1] = f["y"][ok] * 1e3
        pos[fi, k, 2] = f["z"][ok] * 1e3
        r[k] = f["radius"][ok] * 1e3
    arrays = dict(t=np.asarray(t, dtype=np.float32), pos=np.asfortranarray(pos.astype(np.float16)),
                  r=r.astype(np.float32), id=ids.astype(np.int32))
    if extra:
        arrays.update(extra)
    np.savez_compressed(path, **arrays)
    size = os.path.getsize(path)
    if size > max_bytes and F > 40:
        # drop every other frame until it fits
        keep = list(range(0, F, 2))
        return save_frames(path, np.asarray(t)[keep], [frames[i] for i in keep], extra, max_frames,
                           max_bytes, nmax)
    return size


def write_json(path, obj):
    def conv(o):
        if isinstance(o, (np.floating,)):
            return float(o)
        if isinstance(o, (np.integer,)):
            return int(o)
        if isinstance(o, np.ndarray):
            return o.tolist()
        raise TypeError(type(o))
    with open(path, "w") as f:
        json.dump(obj, f, indent=1, default=conv)


def read_json(path, default=None):
    try:
        with open(path) as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


