FeatureScript 3083;
import(path : "onshape/std/common.fs", version : "3083.0");

// Servo pinion of the powder doser as a native Onshape feature tree (issue #172), written for fsgen 0.2.0.
// Same part as cad/text-to-cad/src/parts/servo_pinion.py (PR #176), which matches the lab's Fusion 360 part
// (SpurGear add-in: module 1.298, 14 teeth, 20 deg, zero backlash) on an MG996R servo output:
// axis +Z, faces at z = 0 and z = #gearWidth, tooth 0 centred on +X. Outside diameter (14 + 2) x 1.298 =
// 20.768 mm; it meshes the mounting plate's 28T gears (same module) at 27.258 mm centres.
//   Body         gear blank with the servo interface, one revolved half-section: the MG996R's 25T output
//                spline goes into a plain socket in the z = #gearWidth face (the reference models no spline
//                teeth); the M3 horn screw passes through a hole from the z = 0 face, its head in a 60 deg
//                countersink
//   Gear teeth   one tooth gap (sketch generated by ../gear_gap.py for module 1.298, 14 teeth), cut through
//                and patterned 14 times; tooth count and module are fixed by that sketch
export function build(context is Context, id is Id)
{
    // ---------- variables (one Variable Studio) ----------
    variable(context, "gearWidth", 12.3 * millimeter);           // face width
    variable(context, "outsideDiameter", 20.768 * millimeter);   // (14 + 2) x module 1.298; less tops the teeth, more needs a new gap sketch
    variable(context, "splineSocketDiameter", 6 * millimeter);   // MG996R output spline (about 5.9 mm), plain bore
    variable(context, "splineSocketDepth", 3.5 * millimeter);    // from the z = #gearWidth face
    variable(context, "screwHoleDiameter", 3.4 * millimeter);    // M3 horn screw clearance
    variable(context, "headRecessDiameter", 6.94 * millimeter);  // countersink diameter at the z = 0 face (60 deg included)
    variable(context, "headRecessDepth", 1.77 * millimeter);

    const mm = millimeter;
    const zero = 0 * millimeter;
    const TAN30 = 0.5773502691896258;                            // tan(60 deg / 2): countersink flank, radius per depth
    const topPlane = qCreatedBy(makeId("Top"), EntityType.FACE);
    const frontPlane = qCreatedBy(makeId("Front"), EntityType.FACE);

    // ---------- gear blank with socket, screw hole and countersink: half-section on the Front plane
    //            (sketch x -> world X = radius, sketch y -> world Z) ----------
    const rRecess = #headRecessDiameter / 2;
    const zSocket = #gearWidth - #splineSocketDepth;
    var bodySk = newSketch(context, id + "Body sketch", { "sketchPlane" : frontPlane });
    skPolyline(bodySk, "section", { "points" : [
            vector(rRecess, zero), vector(#outsideDiameter / 2, zero), vector(#outsideDiameter / 2, #gearWidth),
            vector(#splineSocketDiameter / 2, #gearWidth), vector(#splineSocketDiameter / 2, zSocket),
            vector(#screwHoleDiameter / 2, zSocket), vector(#screwHoleDiameter / 2, #headRecessDepth),
            vector(rRecess - #headRecessDepth * TAN30, #headRecessDepth), vector(rRecess, zero)] });
    skLineSegment(bodySk, "axis", { "start" : vector(zero, zero), "end" : vector(zero, 10 * mm), "construction" : true });
    skSolve(bodySk);
    const axis = sketchEntityQuery(id + "Body sketch", EntityType.EDGE, "axis");
    revolve(context, id + "Body", {
        "entities" : qSketchRegion(id + "Body sketch"),
        "axis" : axis,
        "fullRevolve" : true });

    // ---------- teeth: one tooth gap (between tooth 0 on +X and tooth 1) cut through, patterned round the axis ----------
    // flanks: 2 arcs each, within 2.1 um of the involute; radial run from the base circle to the 0.5 mm root fillet
    var gapSk = newSketch(context, id + "Tooth gap sketch", { "sketchPlane" : topPlane });
    // ---- generated by gear_gap.py (module 1.298, 14 teeth, 20 deg); do not edit by hand ----
    skArc(gapSk, "flankA2", { "start" : vector(10.883944745, 0.034681343) * mm, "mid" : vector(10.028392492, 0.624790698) * mm, "end" : vector(9.062670216, 1.008951073) * mm });
    skArc(gapSk, "flankA1", { "start" : vector(9.062670216, 1.008951073) * mm, "mid" : vector(8.768725790, 1.068320009) * mm, "end" : vector(8.469171924, 1.082301302) * mm });
    skLineSegment(gapSk, "radialA", { "start" : vector(8.469171924, 1.082301302) * mm, "end" : vector(8.003647582, 1.022810527) * mm });
    skArc(gapSk, "filletA", { "start" : vector(8.003647582, 1.022810527) * mm, "mid" : vector(7.646765863, 1.113984095) * mm, "end" : vector(7.449169501, 1.424842356) * mm });
    skArc(gapSk, "rootLand", { "start" : vector(7.449169501, 1.424842356) * mm, "mid" : vector(7.394061921, 1.687646383) * mm, "end" : vector(7.329685741, 1.948334912) * mm });
    skArc(gapSk, "filletB", { "start" : vector(7.329685741, 1.948334912) * mm, "mid" : vector(7.372837567, 2.314142376) * mm, "end" : vector(7.654818157, 2.551132097) * mm });
    skLineSegment(gapSk, "radialB", { "start" : vector(7.654818157, 2.551132097) * mm, "end" : vector(8.100053176, 2.699516203) * mm });
    skArc(gapSk, "flankB1", { "start" : vector(8.100053176, 2.699516203) * mm, "mid" : vector(8.363875629, 2.842084464) * mm, "end" : vector(8.602951188, 3.023111734) * mm });
    skArc(gapSk, "flankB2", { "start" : vector(8.602951188, 3.023111734) * mm, "mid" : vector(9.306355955, 3.788239464) * mm, "end" : vector(9.821143046, 4.691119832) * mm });
    skLineSegment(gapSk, "outside", { "start" : vector(9.821143046, 4.691119832) * mm, "end" : vector(10.883944745, 0.034681343) * mm });
    // ---- end of generated block ----
    skSolve(gapSk);
    extrude(context, id + "Tooth gap", {
        "entities" : qSketchRegion(id + "Tooth gap sketch"),
        "operationType" : NewBodyOperationType.REMOVE,
        "endBound" : BoundingType.THROUGH_ALL,
        "defaultScope" : true });
    circularPattern(context, id + "Gear teeth", {
        "patternType" : PatternType.FEATURE,
        "instanceFunction" : [id + "Tooth gap"],
        "axis" : axis,
        "angle" : 360 * degree,
        "instanceCount" : 14,
        "equalSpace" : true });
}
