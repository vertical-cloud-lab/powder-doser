FeatureScript 3083;
import(path : "onshape/std/common.fs", version : "3083.0");

// Stepper pinion of the powder doser as a native Onshape feature tree (issue #172), written for fsgen 0.2.0.
// Same part as cad/text-to-cad/src/parts/stepper_pinion.py (PR #176), which matches the lab's Fusion 360 part
// (SpurGear add-in: module 1, 20 teeth, 20 deg, zero backlash) on the NEMA 11 stepper shaft:
// axis +Z, gear face z = 0 .. #gearWidth, hub on top to z = #pinionLength, tooth 0 centred on +X.
// It meshes the auger tube's 44T gear at 32 mm centres.
//   Body         gear blank and hub, one revolved half-section
//   D bore       shaft circle minus a box beyond the flat (#flatOffset from the axis, on +Y), cut through
//   Gear teeth   one tooth gap (sketch generated by ../gear_gap.py for module 1, 20 teeth), cut through and
//                patterned 20 times; tooth count and module are fixed by that sketch
export function build(context is Context, id is Id)
{
    // ---------- variables (one Variable Studio) ----------
    variable(context, "gearWidth", 10 * millimeter);          // face width
    variable(context, "pinionLength", 16.1 * millimeter);     // gear + hub
    variable(context, "outsideDiameter", 22 * millimeter);    // (20 + 2) x module 1; less tops the teeth, more needs a new gap sketch
    variable(context, "hubDiameter", 9 * millimeter);
    variable(context, "boreDiameter", 5.2 * millimeter);      // NEMA 11 shaft (5 mm) + clearance
    variable(context, "flatOffset", 2.1 * millimeter);        // D-flat distance from the axis, on +Y

    const mm = millimeter;
    const zero = 0 * millimeter;
    const topPlane = qCreatedBy(makeId("Top"), EntityType.FACE);
    const frontPlane = qCreatedBy(makeId("Front"), EntityType.FACE);

    // ---------- gear blank and hub: half-section on the Front plane (sketch x -> world X = radius, y -> world Z) ----------
    var bodySk = newSketch(context, id + "Body sketch", { "sketchPlane" : frontPlane });
    skPolyline(bodySk, "section", { "points" : [
            vector(zero, zero), vector(#outsideDiameter / 2, zero), vector(#outsideDiameter / 2, #gearWidth),
            vector(#hubDiameter / 2, #gearWidth), vector(#hubDiameter / 2, #pinionLength), vector(zero, #pinionLength),
            vector(zero, zero)] });
    skLineSegment(bodySk, "axis", { "start" : vector(zero, zero), "end" : vector(zero, 10 * mm), "construction" : true });
    skSolve(bodySk);
    const axis = sketchEntityQuery(id + "Body sketch", EntityType.EDGE, "axis");
    revolve(context, id + "Body", {
        "entities" : qSketchRegion(id + "Body sketch"),
        "axis" : axis,
        "fullRevolve" : true });

    // ---------- D bore: shaft circle minus a box on the far side of the flat (the source's construction); circle
    //            and box make three regions, and the one round the axis is cut through ----------
    var boreSk = newSketch(context, id + "D bore sketch", { "sketchPlane" : topPlane });
    skCircle(boreSk, "bore", { "center" : vector(zero, zero), "radius" : #boreDiameter / 2 });
    skRectangle(boreSk, "flat", { "firstCorner" : vector(#boreDiameter / 2 + 1 * mm, #flatOffset),
                "secondCorner" : vector(-#boreDiameter / 2 - 1 * mm, #boreDiameter / 2 + 1 * mm) });
    skSolve(boreSk);
    extrude(context, id + "D bore", {
        "entities" : qContainsPoint(qSketchRegion(id + "D bore sketch"), vector(0, 0, 0) * millimeter),
        "operationType" : NewBodyOperationType.REMOVE,
        "endBound" : BoundingType.THROUGH_ALL,
        "defaultScope" : false,
        "booleanScope" : qCreatedBy(id + "Body", EntityType.BODY) });

    // ---------- teeth: one tooth gap (between tooth 0 on +X and tooth 1) cut through, patterned round the axis ----------
    // flanks: 2 arcs each, within 1.6 um of the involute; radial run from the base circle to the 0.5 mm root fillet
    var gapSk = newSketch(context, id + "Tooth gap sketch", { "sketchPlane" : topPlane });
    // ---- generated by gear_gap.py (module 1, 20 teeth, 20 deg); do not edit by hand ----
    skArc(gapSk, "flankA2", { "start" : vector(11.499998828, 0.005192071) * mm, "mid" : vector(10.722126501, 0.493470255) * mm, "end" : vector(9.860948737, 0.812647009) * mm });
    skArc(gapSk, "flankA1", { "start" : vector(9.860948737, 0.812647009) * mm, "mid" : vector(9.610595274, 0.861697883) * mm, "end" : vector(9.355929925, 0.876810927) * mm });
    skLineSegment(gapSk, "radialA", { "start" : vector(9.355929925, 0.876810927) * mm, "end" : vector(9.288908800, 0.870529900) * mm });
    skArc(gapSk, "filletA", { "start" : vector(9.288908800, 0.870529900) * mm, "mid" : vector(8.933653033, 0.974946661) * mm, "end" : vector(8.747646152, 1.295119991) * mm });
    skArc(gapSk, "rootLand", { "start" : vector(8.747646152, 1.295119991) * mm, "mid" : vector(8.734127996, 1.383349974) * mm, "end" : vector(8.719719963, 1.471439015) * mm });
    skArc(gapSk, "filletB", { "start" : vector(8.719719963, 1.471439015) * mm, "mid" : vector(8.797684018, 1.833421234) * mm, "end" : vector(9.103285777, 2.042507545) * mm });
    skLineSegment(gapSk, "radialB", { "start" : vector(9.103285777, 2.042507545) * mm, "end" : vector(9.168967598, 2.057244599) * mm });
    skArc(gapSk, "flankB1", { "start" : vector(9.168967598, 2.057244599) * mm, "mid" : vector(9.406498551, 2.150313879) * mm, "end" : vector(9.629441289, 2.274327507) * mm });
    skArc(gapSk, "flankB2", { "start" : vector(9.629441289, 2.274327507) * mm, "mid" : vector(10.349838972, 2.844001203) * mm, "end" : vector(10.938753261, 3.548757120) * mm });
    skLineSegment(gapSk, "outside", { "start" : vector(10.938753261, 3.548757120) * mm, "end" : vector(11.499998828, 0.005192071) * mm });
    // ---- end of generated block ----
    skSolve(gapSk);
    extrude(context, id + "Tooth gap", {
        "entities" : qSketchRegion(id + "Tooth gap sketch"),
        "operationType" : NewBodyOperationType.REMOVE,
        "endBound" : BoundingType.THROUGH_ALL,
        "defaultScope" : true });
    circularPattern(context, id + "Gear teeth", {
        "patternType" : PatternType.FEATURE,
        "instanceFunction" : [id + "Tooth gap"],
        "axis" : axis,
        "angle" : 360 * degree,
        "instanceCount" : 20,
        "equalSpace" : true });
}
