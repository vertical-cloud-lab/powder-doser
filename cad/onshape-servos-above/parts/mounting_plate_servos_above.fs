FeatureScript 3083;
import(path : "onshape/std/common.fs", version : "3083.0");

// Mounting plate for the servos-above powder doser (issue #172) as a native Onshape feature tree, pushed with
// fsgen 0.2.0. Same part as text-to-cad's mounting_plate_servos_above.py (PR #176): the lab's Fusion 360 part
// "mountingplate_v2" (mounting_plate.py) with the toothed sector of both tilt gears turned 180 deg about the
// hinge, so the gears mesh servo pinions above the hinge instead of below it.
//
// Frame: the "MP frame" of PR #170's layout.py, so the assembly placement applies as is. The hinge axis is MP Z
// through the origin, which lies in the inner face of the world -X tilt gear; the part spans z = -95.9 .. 12.3
// about its mid-plane z = -41.8 (world x = 0); MP +z is the stepper side (world -X). The floor is a plate
// parallel to XZ with its top 29.25 mm below the hinge, so the auger axis (MP X through (0, -41.8)) is level
// with the hinge once the brackets stand on it.
//   floor           #floorThickness plate: rear section, wide front section with 45 deg chamfers, a tongue
//                   under each knuckle and gear arm (bottom front edge rounded with R = #floorThickness),
//                   three rows of M3 holes
//   knuckles        two hinge knuckles around the M5 hinge screw
//   stepper plate   NEMA 11 plate, crosswise, its pilot #stepperOffset from the auger axis
//   tilt gears      28T, module 1.298, at both ends of the hinge; teeth only on a 206.5 deg sector (turned
//                   180 deg from the lab part), the rest of the rim turned down just under the root circle;
//                   an arm ties each gear to the floor
// The z layout (#knuckleGap, #knuckleWidth, #towerSlot, #gearWidth), the floor, its holes and the stepper plate
// follow the Variable Studio. The arm outline and the gear sketches are numbers: their tangent points and
// involutes need trig, which fsgen cannot carry into Onshape expressions. The gear sketches are generated by
// ../gear_gap_mounting_plate.py (to turn the toothed sector, run it with --turn and paste its block).
// Added features sink SINK into what they join, so no faces only touch.
export function build(context is Context, id is Id)
{
    // ---------- variables (one Variable Studio) ----------
    variable(context, "floorThickness", 6 * millimeter);          // also the round under each tongue's front
    variable(context, "hingeHoleDiameter", 5.7 * millimeter);     // M5 hinge screw: knuckles and gears
    variable(context, "knuckleGap", 32.2 * millimeter);           // between the knuckles' inner faces
    variable(context, "knuckleWidth", 12.5 * millimeter);
    variable(context, "towerSlot", 13.2 * millimeter);            // knuckle to gear: 0.3 + baseplate tower 12.3 + 0.6
    variable(context, "gearWidth", 12.3 * millimeter);            // 28T tilt gears and their arms
    variable(context, "floorHoleDiameter", 3.4 * millimeter);     // M3
    variable(context, "floorHoleSpacing", 48 * millimeter);       // the two rows, across the auger
    variable(context, "rearBracketHoles", 124 * millimeter);      // hole rows, this far behind the hinge (MP -x)
    variable(context, "frontBracketHoles", 58.333 * millimeter);
    variable(context, "collarBaseHoles", 42.333 * millimeter);    // tap-collar base
    variable(context, "stepperPlateBack", 89.333 * millimeter);   // motor-side face of the plate, behind the hinge
    variable(context, "stepperPlateThickness", 6 * millimeter);
    variable(context, "stepperOffset", 32 * millimeter);          // pilot axis from the auger axis (MP +z)
    variable(context, "pilotDiameter", 22 * millimeter);
    variable(context, "motorScrewSpacing", 23 * millimeter);      // NEMA 11 square
    variable(context, "motorScrewDiameter", 3.4 * millimeter);    // M2.5 x 8 motor screws

    const mm = millimeter;
    const zero = 0 * mm;
    const SINK = 0.5 * mm;
    const topPlane = qCreatedBy(makeId("Top"), EntityType.FACE);
    const frontPlane = qCreatedBy(makeId("Front"), EntityType.FACE);
    const rightPlane = qCreatedBy(makeId("Right"), EntityType.FACE);

    const FLOOR_TOP_Y = -29.25 * mm;      // the auger axis (y = 0) lies this far above the floor top
    const FLOOR_BACK_X = -130 * mm;
    const FLOOR_FRONT_X = -37 * mm;       // floor front between the tongues
    const REAR_HALF_WIDTH = 34 * mm;      // narrow rear section, either side of the mid-plane
    // 45 deg chamfers from the rear section to the full width end at these x (the Fusion sketch is not symmetric)
    const CHAMFER_END_X_STEPPER = -36.197553 * mm;   // MP +z side
    const CHAMFER_END_X_OTHER = -37 * mm;
    const TAB_MARGIN = 6 * mm;            // floor tab under the stepper plate, past each of its faces
    const TAB_RADIUS = 6 * mm;            // the tab's two outer corners
    const STEPPER_HALF = 18.1 * mm;       // stepper plate around the pilot axis (top and sides)
    const BOSS_R = 7.5 * mm;              // knuckle boss around the hinge axis
    const ARM_FOOT_X = -25 * mm;          // each arm's outer side meets the floor top here
    const GEAR_TIP_R = 19.47 * mm;        // 28T, module 1.298: outside diameter 38.94

    // ---------- z layout: origin on the world -X gear's inner face, MP +z on the stepper side ----------
    const zGearTop = #gearWidth;                      // -X gear outer face (12.3)
    const zKnuckleTop = -#towerSlot;                  // stepper-side knuckle: -13.2 .. -25.7
    const zKnuckleBottom = zKnuckleTop - #knuckleWidth;
    const zKnuckle2Top = zKnuckleBottom - #knuckleGap;          // other knuckle: -57.9 .. -70.4
    const zKnuckle2Bottom = zKnuckle2Top - #knuckleWidth;
    const zGear2Top = zKnuckle2Bottom - #towerSlot;             // +X gear: -83.6 .. -95.9
    const zGear2Bottom = zGear2Top - #gearWidth;
    const midDepth = #knuckleGap / 2 + #knuckleWidth + #towerSlot;    // mid-plane below the origin (41.8)
    const zMid = -midDepth;
    const chamfer = midDepth + #gearWidth - REAR_HALF_WIDTH;          // 45 deg, rear width to full width

    // ---------- arm (MP x-y plane): a band from the floor top up to the knuckle boss. Its outer side runs from
    //            the foot A (x = ARM_FOOT_X on the floor top) to T, where it touches the boss; its inner side is
    //            parallel through the hinge axis, meets the floor top at B and the boss circle at P. ----------
    const footA = vector(ARM_FOOT_X, FLOOR_TOP_Y);
    const phiT = atan2(FLOOR_TOP_Y, ARM_FOOT_X) - acos(BOSS_R / norm(footA));
    const tanT = BOSS_R * vector(cos(phiT), sin(phiT));
    const armDir = normalize(tanT - footA);                 // foot -> boss
    const footB = vector(FLOOR_TOP_Y * armDir[0] / armDir[1], FLOOR_TOP_Y);
    const pIn = -BOSS_R * armDir;
    const sinkStep = SINK * armDir / armDir[1];             // along the sides, SINK down into the floor
    const footAs = footA - sinkStep;
    const footBs = footB - sinkStep;
    const tongueTip = footB[0];                             // the tongues end under the arms' inner side
    // the knuckle's 270 deg boss arc: fsgen pins any sketch point within 1 nm of the origin to it and also
    // dimensions both arc ends, which would over-define an arc centred on the hinge axis (Onshape: WARNING, and
    // fsgen re-sends the sketch without dimensions), so its centre sits 0.1 um off the axis, on the bisector
    const farDir = -normalize(pIn + tanT);
    const hub = 0.0001 * mm * farDir;
    const bossMid = hub + norm(pIn - hub) * farDir;

    // ---------- floor: the side profile (6 mm plate, tongue fronts rounded) across the full width,
    //            intersected with the plan outline ----------
    cPlane(context, id + "Hinge mid plane", { "entities" : topPlane, "offset" : midDepth, "oppositeDirection" : true });
    const midPlane = qCreatedBy(id + "Hinge mid plane", EntityType.FACE);
    var sideSk = newSketch(context, id + "Floor side profile sketch", { "sketchPlane" : midPlane });
    const floorBottomY = FLOOR_TOP_Y - #floorThickness;
    skPolyline(sideSk, "plate", { "points" : [
            vector(tongueTip, FLOOR_TOP_Y), vector(FLOOR_BACK_X - 1 * mm, FLOOR_TOP_Y),
            vector(FLOOR_BACK_X - 1 * mm, floorBottomY), vector(tongueTip - #floorThickness, floorBottomY)] });
    skArc(sideSk, "tongueRound", { "start" : vector(tongueTip - #floorThickness, floorBottomY),
                "mid" : vector(tongueTip - #floorThickness * 0.2928932188, FLOOR_TOP_Y - #floorThickness * 0.7071067812),
                "end" : vector(tongueTip, FLOOR_TOP_Y) });
    skSolve(sideSk);
    extrude(context, id + "Floor", {
        "entities" : qSketchRegion(id + "Floor side profile sketch"),
        "operationType" : NewBodyOperationType.NEW,
        "endBound" : BoundingType.BLIND,
        "depth" : 2 * (midDepth + #gearWidth) + 2 * mm,
        "symmetric" : true });

    // plan on the Front plane (sketch x -> MP x, sketch y -> MP z); the tongues run SINK past the arms' inner
    // side, so the side profile's round alone shapes their fronts. The hinge axis is a construction line here.
    var outlineSk = newSketch(context, id + "Floor outline sketch", { "sketchPlane" : frontPlane });
    const tipX = tongueTip + SINK;
    const tab0 = -#stepperPlateBack - TAB_MARGIN;
    const tab1 = -#stepperPlateBack + #stepperPlateThickness + TAB_MARGIN;
    skPolyline(outlineSk, "rear", { "points" : [
            vector(CHAMFER_END_X_OTHER - chamfer, zMid - REAR_HALF_WIDTH),
            vector(FLOOR_BACK_X, zMid - REAR_HALF_WIDTH), vector(FLOOR_BACK_X, zMid + REAR_HALF_WIDTH),
            vector(tab0, zMid + REAR_HALF_WIDTH), vector(tab0, zGearTop - TAB_RADIUS)] });
    skArc(outlineSk, "tabCorner0", { "start" : vector(tab0, zGearTop - TAB_RADIUS),
                "mid" : vector(tab0 + TAB_RADIUS * 0.2928932188, zGearTop - TAB_RADIUS * 0.2928932188),
                "end" : vector(tab0 + TAB_RADIUS, zGearTop) });
    skLineSegment(outlineSk, "tabEdge", { "start" : vector(tab0 + TAB_RADIUS, zGearTop), "end" : vector(tab1 - TAB_RADIUS, zGearTop) });
    skArc(outlineSk, "tabCorner1", { "start" : vector(tab1 - TAB_RADIUS, zGearTop),
                "mid" : vector(tab1 - TAB_RADIUS * 0.2928932188, zGearTop - TAB_RADIUS * 0.2928932188),
                "end" : vector(tab1, zGearTop - TAB_RADIUS) });
    skPolyline(outlineSk, "front", { "points" : [
            vector(tab1, zGearTop - TAB_RADIUS), vector(tab1, zMid + REAR_HALF_WIDTH),
            vector(CHAMFER_END_X_STEPPER - chamfer, zMid + REAR_HALF_WIDTH), vector(CHAMFER_END_X_STEPPER, zGearTop),
            vector(tipX, zGearTop), vector(tipX, zero),                            // gear tongue
            vector(FLOOR_FRONT_X, zero), vector(FLOOR_FRONT_X, zKnuckleTop),
            vector(tipX, zKnuckleTop), vector(tipX, zKnuckleBottom),               // knuckle tongue
            vector(FLOOR_FRONT_X, zKnuckleBottom), vector(FLOOR_FRONT_X, zKnuckle2Top),
            vector(tipX, zKnuckle2Top), vector(tipX, zKnuckle2Bottom),             // knuckle tongue
            vector(FLOOR_FRONT_X, zKnuckle2Bottom), vector(FLOOR_FRONT_X, zGear2Top),
            vector(tipX, zGear2Top), vector(tipX, zGear2Bottom),                   // gear tongue
            vector(CHAMFER_END_X_OTHER, zGear2Bottom), vector(CHAMFER_END_X_OTHER - chamfer, zMid - REAR_HALF_WIDTH)] });
    // M3 rows: brackets and the tap-collar base, #floorHoleSpacing apart across the auger
    for (var row in [["Rear", #rearBracketHoles], ["Front", #frontBracketHoles], ["Collar", #collarBaseHoles]])
    {
        for (var side in [-1, 1])
        {
            skCircle(outlineSk, "hole" ~ row[0] ~ (side > 0 ? "Stepper" : "Other"), {
                        "center" : vector(-row[1], zMid + side * #floorHoleSpacing / 2), "radius" : #floorHoleDiameter / 2 });
        }
    }
    skLineSegment(outlineSk, "hingeAxis", { "start" : vector(zero, zero), "end" : vector(zero, 10 * mm), "construction" : true });
    skSolve(outlineSk);
    const hingeAxis = sketchEntityQuery(id + "Floor outline sketch", EntityType.EDGE, "hingeAxis");
    extrude(context, id + "Floor outline", {
        "entities" : qSketchRegion(id + "Floor outline sketch", true),
        "operationType" : NewBodyOperationType.INTERSECT,
        "endBound" : BoundingType.BLIND,
        "depth" : -FLOOR_TOP_Y + #floorThickness + 1 * mm,     // from the Front plane (y = 0) down past the floor
        "defaultScope" : false,
        "booleanScope" : qCreatedBy(id + "Floor", EntityType.BODY) });

    // ---------- NEMA 11 stepper plate: crosswise (normal MP x), sketch x -> MP y, sketch y -> MP z ----------
    cPlane(context, id + "Stepper plate plane", { "entities" : rightPlane, "offset" : #stepperPlateBack, "oppositeDirection" : true });
    var stepperSk = newSketch(context, id + "Stepper plate sketch", { "sketchPlane" : qCreatedBy(id + "Stepper plate plane", EntityType.FACE) });
    const pilotZ = zMid + #stepperOffset;
    skRectangle(stepperSk, "plate", { "firstCorner" : vector(FLOOR_TOP_Y - SINK, pilotZ - STEPPER_HALF),
                "secondCorner" : vector(STEPPER_HALF, pilotZ + STEPPER_HALF) });
    skCircle(stepperSk, "pilot", { "center" : vector(zero, pilotZ), "radius" : #pilotDiameter / 2 });
    for (var sy in [-1, 1])
    {
        for (var sz in [-1, 1])
        {
            skCircle(stepperSk, "screw" ~ (sy > 0 ? "Top" : "Bottom") ~ (sz > 0 ? "Stepper" : "Other"), {
                        "center" : vector(sy * #motorScrewSpacing / 2, pilotZ + sz * #motorScrewSpacing / 2),
                        "radius" : #motorScrewDiameter / 2 });
        }
    }
    skSolve(stepperSk);
    extrude(context, id + "Stepper plate", {
        "entities" : qSketchRegion(id + "Stepper plate sketch", true),
        "operationType" : NewBodyOperationType.ADD,
        "endBound" : BoundingType.BLIND,
        "depth" : #stepperPlateThickness,
        "defaultScope" : false,
        "booleanScope" : qCreatedBy(id + "Floor", EntityType.BODY) });

    // ---------- tilt gears: blank, mirrored to the other end of the hinge, then both cut at once ----------
    // (the knuckles and arms come later, so the tooth gaps and the sector cut can go through all)
    var blankSk = newSketch(context, id + "Gear blank sketch", { "sketchPlane" : topPlane });
    skCircle(blankSk, "tip", { "center" : vector(zero, zero), "radius" : GEAR_TIP_R });
    skCircle(blankSk, "bore", { "center" : vector(zero, zero), "radius" : #hingeHoleDiameter / 2 });
    skSolve(blankSk);
    extrude(context, id + "Gear blank", {
        "entities" : qSketchRegion(id + "Gear blank sketch", true),
        "operationType" : NewBodyOperationType.NEW,
        "endBound" : BoundingType.BLIND,
        "depth" : #gearWidth });
    mirror(context, id + "Mirror gear blank", {
        "patternType" : PatternType.FEATURE,
        "instanceFunction" : [id + "Gear blank"],
        "mirrorPlane" : midPlane });

    // one tooth gap (between tooth 0 on +X and tooth 1), patterned 28 times
    var gapSk = newSketch(context, id + "Tooth gap sketch", { "sketchPlane" : topPlane });
    // ---- generated by gear_gap_mounting_plate.py (tooth gap: module 1.298, 28 teeth, 20 deg); do not edit by hand ----
    skArc(gapSk, "flankA1", { "start" : vector(19.969054846, 0.194289850) * mm, "mid" : vector(19.221361411, 0.595311275) * mm, "end" : vector(18.563948458, 0.876443268) * mm });
    skArc(gapSk, "flankA2", { "start" : vector(18.563948458, 0.876443268) * mm, "mid" : vector(18.011188327, 1.057170965) * mm, "end" : vector(17.574685222, 1.158494781) * mm });
    skArc(gapSk, "flankA3", { "start" : vector(17.574685222, 1.158494781) * mm, "mid" : vector(17.263127631, 1.202591259) * mm, "end" : vector(17.082179218, 1.212460388) * mm });
    skArc(gapSk, "filletA", { "start" : vector(17.082179218, 1.212460388) * mm, "mid" : vector(16.748247210, 1.342504456) * mm, "end" : vector(16.587098530, 1.662587489) * mm });
    skLineSegment(gapSk, "rootLand", { "start" : vector(16.587098530, 1.662587489) * mm, "end" : vector(16.541185860, 2.070073707) * mm });
    skArc(gapSk, "filletB", { "start" : vector(16.541185860, 2.070073707) * mm, "mid" : vector(16.627069030, 2.417990545) * mm, "end" : vector(16.923691138, 2.619080999) * mm });
    skArc(gapSk, "flankB1", { "start" : vector(16.923691138, 2.619080999) * mm, "mid" : vector(17.097906710, 2.668967499) * mm, "end" : vector(17.391840512, 2.781286472) * mm });
    skArc(gapSk, "flankB2", { "start" : vector(17.391840512, 2.781286472) * mm, "mid" : vector(17.794852902, 2.977200966) * mm, "end" : vector(18.293538486, 3.276398143) * mm });
    skArc(gapSk, "flankB3", { "start" : vector(18.293538486, 3.276398143) * mm, "mid" : vector(18.871910971, 3.696769715) * mm, "end" : vector(19.511622508, 4.254114137) * mm });
    skLineSegment(gapSk, "outside", { "start" : vector(19.511622508, 4.254114137) * mm, "end" : vector(19.969054846, 0.194289850) * mm });
    // ---- end of generated tooth gap ----
    skSolve(gapSk);
    extrude(context, id + "Tooth gap", {
        "entities" : qSketchRegion(id + "Tooth gap sketch"),
        "operationType" : NewBodyOperationType.REMOVE,
        "endBound" : BoundingType.THROUGH_ALL,
        "hasSecondDirection" : true,
        "secondDirectionBound" : BoundingType.THROUGH_ALL,
        "defaultScope" : true });
    circularPattern(context, id + "Gear teeth", {
        "patternType" : PatternType.FEATURE,
        "instanceFunction" : [id + "Tooth gap"],
        "axis" : hingeAxis,
        "angle" : 360 * degree,
        "instanceCount" : 28,
        "equalSpace" : true });

    // teeth only on the toothed sector: elsewhere the rim is turned down just under the root circle
    var sectorSk = newSketch(context, id + "Toothless sector sketch", { "sketchPlane" : topPlane });
    // ---- generated by gear_gap_mounting_plate.py (toothless sector, turned 180 deg: 277.076 -> 70.563 deg); do not edit by hand ----
    skLineSegment(sectorSk, "startSide", { "start" : vector(2.049257357, -16.508797792) * mm, "end" : vector(2.956459173, -23.817206997) * mm });
    skPolyline(sectorSk, "outside", { "points" : [vector(2.956459173, -23.817206997) * mm, vector(17.102663263, -16.837425851) * mm, vector(23.860503907, -2.583864022) * mm, vector(20.310588844, 12.785929017) * mm, vector(7.986484061, 22.632191064) * mm] });
    skLineSegment(sectorSk, "endSide", { "start" : vector(7.986484061, 22.632191064) * mm, "end" : vector(5.535798150, 15.687408935) * mm });
    skArc(sectorSk, "turnedRim", { "start" : vector(5.535798150, 15.687408935) * mm, "mid" : vector(16.538885486, -1.791002878) * mm, "end" : vector(2.049257357, -16.508797792) * mm });
    // ---- end of generated toothless sector ----
    skSolve(sectorSk);
    extrude(context, id + "Toothless sector", {
        "entities" : qSketchRegion(id + "Toothless sector sketch"),
        "operationType" : NewBodyOperationType.REMOVE,
        "endBound" : BoundingType.THROUGH_ALL,
        "hasSecondDirection" : true,
        "secondDirectionBound" : BoundingType.THROUGH_ALL,
        "defaultScope" : true });

    // ---------- stepper-side knuckle: arm + boss around the hinge screw ----------
    cPlane(context, id + "Knuckle plane", { "entities" : topPlane, "offset" : #towerSlot + #knuckleWidth, "oppositeDirection" : true });
    var knuckleSk = newSketch(context, id + "Knuckle sketch", { "sketchPlane" : qCreatedBy(id + "Knuckle plane", EntityType.FACE) });
    skLineSegment(knuckleSk, "foot", { "start" : footAs, "end" : footBs });
    skLineSegment(knuckleSk, "innerSide", { "start" : footBs, "end" : pIn });
    skArc(knuckleSk, "boss", { "start" : pIn, "mid" : bossMid, "end" : tanT });
    skLineSegment(knuckleSk, "outerSide", { "start" : tanT, "end" : footAs });
    skCircle(knuckleSk, "bore", { "center" : vector(zero, zero), "radius" : #hingeHoleDiameter / 2 });
    skSolve(knuckleSk);
    extrude(context, id + "Knuckle", {
        "entities" : qSketchRegion(id + "Knuckle sketch", true),
        "operationType" : NewBodyOperationType.ADD,
        "endBound" : BoundingType.BLIND,
        "depth" : #knuckleWidth,
        "defaultScope" : true });

    // ---------- arm from the -X gear down to the floor: the same band, up to the chord P-T inside the gear ----------
    var armSk = newSketch(context, id + "Gear arm sketch", { "sketchPlane" : topPlane });
    skPolyline(armSk, "arm", { "points" : [footAs, footBs, pIn, tanT, footAs] });
    skSolve(armSk);
    extrude(context, id + "Gear arm", {
        "entities" : qSketchRegion(id + "Gear arm sketch"),
        "operationType" : NewBodyOperationType.ADD,
        "endBound" : BoundingType.BLIND,
        "depth" : #gearWidth,
        "defaultScope" : true });

    // ---------- the other knuckle and gear arm ----------
    mirror(context, id + "Mirror knuckle and gear arm", {
        "patternType" : PatternType.FEATURE,
        "instanceFunction" : [id + "Knuckle", id + "Gear arm"],
        "mirrorPlane" : midPlane });
}
