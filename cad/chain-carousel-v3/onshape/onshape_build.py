"""Put the chain-carousel test rig v3 into Onshape as a kept copy (issue #128, PR #185).

    python onshape_build.py create      # new public company document + import + views + version
    python onshape_build.py resume      # finish a create that stopped part way (re-poll, views, version)
    python onshape_build.py views       # re-render Onshape's shaded views of the recorded document

Sam asked on 2026-11-10 to keep a copy of every version in Onshape. This is v5's route
(../../chain-carousel-v5/onshape/onshape_build.py): one composite import of ../step/chain_carousel_rig_v3.step
(flattenAssemblies false) gives an Assembly tab whose tree is the build sequence (one sub-assembly per
assembly step) plus Part Studios for the unique parts, with every instance already placed. The top assembly
is the ASSEMBLY tab named like the STEP's root product. Ids land in onshape_document.json; every call is in
api_calls.jsonl.
"""
from __future__ import annotations

import argparse
import base64
import difflib
import hashlib
import json
import re
import subprocess
import time
from pathlib import Path

import requests

from client import HERE, Onshape

ROOT = HERE.parent
REPO = ROOT.parent.parent
STEP = ROOT / "step" / "chain_carousel_rig_v3.step"
DOC_JSON = HERE / "onshape_document.json"
RENDERS = ROOT / "renders" / "onshape"
COMPANY_NAME = "Vertical Cloud Lab"
RUN = "create-document-v3"
# 7 calls + the polls + 1 spare. A 21 MB STEP; v5's 40 MB was done 3.5-4.5 min after the upload.
BUDGET, FIRST_WAIT, POLLS = 16, 120, 8
DOC_NAME = "Multi-doser chain carousel - test rig v3, kinematic dock, augers inside the loop (#128)"
DESCRIPTION = ("v2 with Sam's review of 2026-10-29, items 1-6; the augers still ride inside the loop. Two ANSI #35 "
               "chains (104 links each) round four 32T corner shafts; 13 carriages on A-1 tabs carry Sam's Oct 13 "
               "mounting plate and the lab auger. The electronics carriage docks on a Kelvin clamp (cone, dowel vee, "
               "steel flat) held by two N52 magnets and an electromagnet, parks in a guide cradle and is lifted by an "
               "Actuonix P16; a spring door on each auger's outlet opens only while docked; a bolt latch holds each "
               "plate upside down until a station rail draws it back; acrylic enclosure with two hatches. The HR-100A "
               "is drawn at the dose point but doesn't fit. Generated by vertical-cloud-lab/powder-doser "
               "cad/chain-carousel-v3 (CadQuery -> STEP -> REST API).")
VERSION_NAME = "v3 kinematic dock"      # name, note and the document's text kept to lengths Onshape has taken
VERSION_NOTE = ("Import of cad/chain-carousel-v3 at {commit} (#128, PR #185): 881 instances, 93 unique parts; 0 clashes "
                "over 0.5 mm^3 at home, tilted to 90 deg, at the swap and over a one-module sweep; the HR-100A doesn't "
                "fit")
FRONT_ISO = "0.743,-0.669,0,0,0.339,0.376,0.862,0,-0.577,-0.641,0.507,0"   # from the front-left, above
VIEWS = (("iso", "isometric"), ("front_iso", FRONT_ISO))


def save(rec: dict) -> None:
    DOC_JSON.write_text(json.dumps(rec, indent=1))


def step_info() -> dict:
    """What gets imported: its size, sha256, the last commit that touched it and its root product's name."""
    data = STEP.read_bytes()
    git = lambda *a: subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    commit = git("log", "-1", "--format=%H", "--", str(STEP))[:7] or "uncommitted"
    if git("status", "--porcelain", "--", str(STEP)):
        commit += " with local edits"
    m = re.search(rb"=\s*PRODUCT\s*\(\s*'((?:[^']|'')*)'", data[:1 << 16])     # OCC writes the root first
    root = " ".join(m.group(1).decode("latin-1").replace("''", "'").split()) if m else STEP.stem
    return {"step": str(STEP.relative_to(REPO)), "stepBytes": len(data),
            "stepSha256": hashlib.sha256(data).hexdigest(), "stepCommit": commit, "stepRoot": root}


def company_id(c: Onshape) -> str:
    for it in c.get("/companies")["items"]:
        if it["name"] == COMPANY_NAME:
            return it["id"]
    raise RuntimeError(f"the API key is not in {COMPANY_NAME}")


def upload(c: Onshape, did: str, wid: str) -> str:
    data = STEP.read_bytes()
    form = {"encodedFilename": STEP.name, "fileContentLength": str(len(data)), "translate": "true",
            "flattenAssemblies": "false", "yAxisIsUp": "false", "allowFaultyParts": "true"}
    res = c.post(f"/blobelements/d/{did}/w/{wid}", files={"file": (STEP.name, data, "application/step")}, data=form)
    return res.get("translationId") or res["id"]


def wait_translation(c: Onshape, tid: str, first_wait: int) -> dict:
    print("translation", tid, flush=True)
    time.sleep(first_wait)
    for i in range(POLLS):                       # about once a minute
        if i:
            time.sleep(60)
        st = c.get(f"/translations/{tid}")
        print("  ", st["requestState"], time.strftime("%H:%M:%S"), flush=True)
        if st["requestState"] == "DONE":
            return st
        if st["requestState"] == "FAILED":
            raise RuntimeError(f"translation failed: {st.get('failureReason')}")
    raise RuntimeError(f"translation {tid} still running after {POLLS} polls; run 'resume' later")


def pick_top(asm: list[dict], names: list[str]) -> dict | None:
    """The ASSEMBLY tab named like the STEP's root product (or file), else the closest name, else the first."""
    if not asm:
        return None
    norm = lambda s: " ".join(s.lower().replace("_", " ").split())
    want = [norm(n) for n in names]
    for same in (lambda a, b: a == b, lambda a, b: a.startswith(b)):
        for e in asm:
            if any(same(norm(e["name"]), w) for w in want):
                return e
    score = lambda e: max(difflib.SequenceMatcher(None, norm(e["name"]), w).ratio() for w in want)
    best = max(asm, key=score)
    return best if score(best) >= 0.6 else asm[0]


def shaded(c: Onshape, rec: dict, name: str, view: str, w: int = 1600, h: int = 1000) -> Path:
    did, wid, aid = rec["documentId"], rec["workspaceId"], rec["assemblyElementId"]
    r = c.get(f"/assemblies/d/{did}/w/{wid}/e/{aid}/shadedviews",
              params={"viewMatrix": view, "outputHeight": h, "outputWidth": w, "pixelSize": 0,
                      "edges": "show", "useAntiAliasing": "true"})
    RENDERS.mkdir(parents=True, exist_ok=True)
    out = RENDERS / f"onshape_{name}.png"
    out.write_bytes(base64.b64decode(r["images"][0]))
    return out


def finish(c: Onshape, rec: dict, first_wait: int, keep_views: bool) -> None:
    """Everything after the document exists; skips what rec already records, so 'resume' can rerun it."""
    did, wid = rec["documentId"], rec["workspaceId"]
    if not rec.get("translationId"):
        rec["translationId"] = upload(c, did, wid)
        save(rec)
    if not rec.get("assemblyElementId"):
        st = wait_translation(c, rec["translationId"], first_wait)
        rec["importedElementIds"] = st.get("resultElementIds", [])
        els = c.get(f"/documents/d/{did}/w/{wid}/elements")
        rec["elements"] = [{"id": e["id"], "name": e["name"], "type": e.get("elementType")} for e in els]
        top = pick_top([e for e in els if e.get("elementType") == "ASSEMBLY"], [rec["stepRoot"], STEP.stem])
        rec["assemblyElementId"] = top["id"] if top else None
        rec["assemblyName"] = top["name"] if top else None
        rec["assemblyUrl"] = f"{rec['url']}/e/{top['id']}" if top else None
        save(rec)
    if rec["assemblyElementId"]:
        for name, view in VIEWS:
            if keep_views and (RENDERS / f"onshape_{name}.png").exists():
                continue
            try:
                print("->", shaded(c, rec, name, view), flush=True)
            except (RuntimeError, requests.RequestException) as e:
                print("view", name, "failed:", str(e)[:200], flush=True)
    if not rec.get("version"):
        v = c.post(f"/documents/d/{did}/versions", json={"documentId": did, "name": VERSION_NAME,
                                                         "description": VERSION_NOTE.format(commit=rec["stepCommit"])})
        rec["version"] = {"id": v["id"], "name": v["name"]}


def report(rec: dict) -> None:
    for k in ("url", "assemblyName", "assemblyUrl", "version", "api_calls"):
        print(f"{k}: {rec.get(k)}")


def create() -> dict:
    if DOC_JSON.exists():
        raise SystemExit(f"{DOC_JSON.name} already records a document: use 'resume' or 'views', or move it aside")
    c = Onshape(budget=BUDGET, run=RUN)
    rec = {"owner": COMPANY_NAME, "public": True, **step_info()}
    try:
        cid = company_id(c)
        doc = c.post("/documents", json={"name": DOC_NAME, "ownerId": cid, "ownerType": 1, "isPublic": True,
                                         "description": DESCRIPTION})
        did, wid = doc["id"], doc["defaultWorkspace"]["id"]
        rec = {"documentId": did, "workspaceId": wid, "name": DOC_NAME, **rec,
               "url": f"https://cad.onshape.com/documents/{did}/w/{wid}"}
        save(rec)
        print("document", rec["url"], flush=True)
        finish(c, rec, FIRST_WAIT, keep_views=False)
    finally:
        if "documentId" in rec:
            rec["api_calls"] = c.calls
            save(rec)
    report(rec)
    return rec


def resume() -> dict:
    rec = json.loads(DOC_JSON.read_text())
    c = Onshape(budget=BUDGET, run=RUN.replace("create", "resume"))
    before = rec.get("api_calls", 0)
    try:
        finish(c, rec, 0, keep_views=True)
    finally:
        rec["api_calls"] = before + c.calls
        save(rec)
    report(rec)
    return rec


def views() -> None:
    rec = json.loads(DOC_JSON.read_text())
    c = Onshape(budget=4, run="views")
    for name, view in VIEWS:
        print("->", shaded(c, rec, name, view))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["create", "resume", "views"])
    {"create": create, "resume": resume, "views": views}[ap.parse_args().cmd]()
