"""Tooth-gap sketch for the auger's 44T gear in auger.fs (0 Onshape calls).

fsgen sketches have lines, arcs and circles but no splines, so each involute
flank is one 3-point arc. The gear is the one text-to-cad's
``lib/gears.py`` (PR #176) builds to match the lab's Fusion 360 SpurGear
add-in: module 1, 20 deg pressure angle, addendum 1.0 m, dedendum 1.157 m,
0.5 mm root fillets, zero backlash, tooth 0 centred on +X. The gap between
tooth 0 and tooth 1 is cut once and patterned 44 times in Onshape.

    python tooth_gap.py           # print the block for auger.fs
    python tooth_gap.py --check   # fail if auger.fs holds other numbers

The arc stands in for the involute to within 5.5 um (checked below on 200
points per flank). Every point is in millimetres in the gear plane (sketch
x -> world X, sketch y -> world Y).
"""
from __future__ import annotations

import math
import re
import sys
from pathlib import Path

MODULE, TEETH, PRESSURE_ANGLE = 1.0, 44, 20.0
ADDENDUM, DEDENDUM, ROOT_FILLET = 1.0, 1.157, 0.5
OVERCUT = 0.5          # flank arcs run this far past the tip circle, so the cut crosses it cleanly
FS = Path(__file__).resolve().parent / "auger.fs"


def inv(a: float) -> float:
    return math.tan(a) - a


def gap() -> dict:
    alpha = math.radians(PRESSURE_ANGLE)
    rp = MODULE * TEETH / 2
    rb, ra, rr = rp * math.cos(alpha), rp + ADDENDUM * MODULE, rp - DEDENDUM * MODULE
    psi_b = math.pi / (2 * TEETH) + inv(alpha)

    def pt(r: float) -> tuple[float, float]:        # +Y flank of tooth 0
        a = psi_b - inv(math.acos(min(1.0, rb / r)))
        return (r * math.cos(a), r * math.sin(a))

    # root fillet: centre on radius rr + rho, tangent to the involute (rb < rr for 44 teeth, so no radial run)
    rho, rc = ROOT_FILLET, rr + ROOT_FILLET
    assert rb < rr

    def centre(r: float) -> tuple[float, float]:
        h = 1e-7
        (x0, y0), (x1, y1) = pt(r - h), pt(r + h)
        tx, ty = x1 - x0, y1 - y0
        n = math.hypot(tx, ty)
        x, y = pt(r)
        return (x - rho * ty / n, y + rho * tx / n)

    lo, hi = max(rb, rr), ra
    for _ in range(100):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if math.hypot(*centre(mid)) < rc else (lo, mid)
    r_t = 0.5 * (lo + hi)
    cx, cy = centre(r_t)
    t = pt(r_t)
    k = rr / math.hypot(cx, cy)
    root = (cx * k, cy * k)
    bx, by = (t[0] - cx) + (root[0] - cx), (t[1] - cy) + (root[1] - cy)
    nb = math.hypot(bx, by)
    fillet_mid = (cx + rho * bx / nb, cy + rho * by / nb)

    # flank arc through the involute's ends and its midpoint in roll angle
    r_top = ra + OVERCUT
    roll = lambda r: math.sqrt((r / rb) ** 2 - 1)
    r_mid = rb * math.sqrt(1 + (0.5 * (roll(r_t) + roll(r_top))) ** 2)
    flank = (t, pt(r_mid), pt(r_top))

    # mirror about the gap centre line (angle pi / N)
    phi = math.pi / TEETH
    c2, s2 = math.cos(2 * phi), math.sin(2 * phi)
    mirror = lambda p: (p[0] * c2 + p[1] * s2, p[0] * s2 - p[1] * c2)
    root_mid = (rr * math.cos(phi), rr * math.sin(phi))

    # deviation of the flank arc from the involute between r_t and the tip circle
    (ax, ay), (mx, my), (ex, ey) = flank
    d = 2 * (ax * (my - ey) + mx * (ey - ay) + ex * (ay - my))
    ux = ((ax * ax + ay * ay) * (my - ey) + (mx * mx + my * my) * (ey - ay) + (ex * ex + ey * ey) * (ay - my)) / d
    uy = ((ax * ax + ay * ay) * (ex - mx) + (mx * mx + my * my) * (ax - ex) + (ex * ex + ey * ey) * (mx - ax)) / d
    R = math.hypot(ax - ux, ay - uy)
    dev = max(abs(math.hypot(x - ux, y - uy) - R)
              for x, y in (pt(r_t + (ra - r_t) * i / 200) for i in range(201)))
    assert dev < 6e-3, dev
    return {"flank": flank, "fillet": (t, fillet_mid, root), "root": (root, root_mid, mirror(root)),
            "mirror": mirror, "deviation_mm": dev, "ra": ra, "rr": rr, "r_t": r_t}


def block() -> str:
    g = gap()
    m = g["mirror"]
    v = lambda p: f"vector({p[0]:.9f}, {p[1]:.9f}) * mm"
    (t, fm, fr) = g["fillet"]
    (_, flm, fltop) = g["flank"]
    lines = [
        "    // ---- generated by tooth_gap.py (module 1, 44 teeth, 20 deg); do not edit by hand ----",
        f'    skArc(gapSk, "flankA", {{ "start" : {v(fltop)}, "mid" : {v(flm)}, "end" : {v(t)} }});',
        f'    skArc(gapSk, "filletA", {{ "start" : {v(t)}, "mid" : {v(fm)}, "end" : {v(fr)} }});',
        f'    skArc(gapSk, "rootLand", {{ "start" : {v(fr)}, "mid" : {v(g["root"][1])}, "end" : {v(m(fr))} }});',
        f'    skArc(gapSk, "filletB", {{ "start" : {v(m(fr))}, "mid" : {v(m(fm))}, "end" : {v(m(t))} }});',
        f'    skArc(gapSk, "flankB", {{ "start" : {v(m(t))}, "mid" : {v(m(flm))}, "end" : {v(m(fltop))} }});',
        f'    skLineSegment(gapSk, "outside", {{ "start" : {v(m(fltop))}, "end" : {v(fltop)} }});',
        "    // ---- end of generated block ----",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    g = gap()
    b = block()
    if "--check" in sys.argv:
        src = FS.read_text()
        cur = re.search(r"    // ---- generated by tooth_gap\.py.*?// ---- end of generated block ----", src, re.S)
        if cur is None or cur.group(0) != b:
            sys.exit("auger.fs: tooth-gap block is out of date; run python tooth_gap.py and paste it in")
        print("auger.fs tooth-gap block is current")
    else:
        print(b)
    print(f"// flank arc vs involute: max {g['deviation_mm'] * 1000:.2f} um; root r {g['rr']:.3f}, "
          f"tip r {g['ra']:.3f}, fillet meets flank at r {g['r_t']:.4f}", file=sys.stderr)
